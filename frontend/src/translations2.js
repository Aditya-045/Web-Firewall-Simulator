// Kashmiri, Konkani, Maithili, Sanskrit (coined/adapted technical terms),
// and Sindhi. It is LOWEST for Manipuri (mni, Meitei Mayek script) and
// Santali (sat, Ol Chiki script) specifically -- both scripts are sparsely
// represented in common training data, so these two in particular should
// be reviewed by a native speaker before shipping to production.
//
// To add a language: add a new key below with the same shape as "en", and
