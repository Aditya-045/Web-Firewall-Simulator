//     Telugu, Tamil, Malayalam as applicable).
//
// REVIEW CAVEAT: these were machine-translated, not sourced from native
// speakers. Confidence is reasonably high for languages with large digital
// footprints (Hindi, Bengali, Urdu, Tamil, Telugu, Gujarati, Punjabi,
